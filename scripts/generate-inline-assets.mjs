#!/usr/bin/env node
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, "..");

const srcDir = path.join(repoRoot, "src");
const cardsDir = path.join(srcDir, "cards");
const stylesDir = path.join(srcDir, "styles");
const outFile = path.join(srcDir, "generated", "inline-assets.js");
const fontFile = path.join(repoRoot, "assets", "fonts", "Inter.var.woff2");

async function readText(file) {
  return fs.readFile(file, "utf8");
}

async function readCardAssets() {
  const files = await fs.readdir(cardsDir);
  const tags = files
    .filter((name) => name.endsWith(".html"))
    .map((name) => name.replace(/\.html$/, ""))
    .sort();

  const out = {};
  for (const tag of tags) {
    const htmlPath = path.join(cardsDir, `${tag}.html`);
    const cssPath = path.join(cardsDir, `${tag}.css`);
    try {
      const [html, css] = await Promise.all([readText(htmlPath), readText(cssPath)]);
      out[tag] = { html, css };
    } catch {
      // Skip cards that do not use the html/css pair convention.
    }
  }
  return out;
}

async function readWeatherIcons() {
  const dir = path.join(cardsDir, "weather-icons");
  const files = (await fs.readdir(dir)).filter((name) => name.endsWith(".svg")).sort();
  const out = {};
  for (const file of files) {
    const key = file.replace(/\.svg$/, "");
    out[key] = await readText(path.join(dir, file));
  }
  return out;
}

function buildThemeCss(themeCss, typographyCss) {
  return themeCss.replace(/@import\s+["']\.\/typography\.css["'];?\s*/g, `${typographyCss}\n`);
}

async function readFontDataUrl() {
  try {
    const buf = await fs.readFile(fontFile);
    return `data:font/woff2;base64,${buf.toString("base64")}`;
  } catch {
    return "";
  }
}

async function main() {
  const [baseCss, themeCss, typographyCss, cardAssets, weatherIcons, fontDataUrl] = await Promise.all([
    readText(path.join(stylesDir, "jelly-base-card.css")),
    readText(path.join(stylesDir, "jelly-theme.css")),
    readText(path.join(stylesDir, "typography.css")),
    readCardAssets(),
    readWeatherIcons(),
    readFontDataUrl(),
  ]);

  const mergedThemeCss = buildThemeCss(themeCss, typographyCss);

  const file = `/* Auto-generated by scripts/generate-inline-assets.mjs. Do not edit manually. */\n\nexport const JELLY_BASE_CSS = ${JSON.stringify(baseCss)};\n\nexport const JELLY_THEME_CSS = ${JSON.stringify(mergedThemeCss)};\n\nexport const JELLY_CARD_ASSETS = ${JSON.stringify(cardAssets, null, 2)};\n\nexport const JELLY_WEATHER_ICONS = ${JSON.stringify(weatherIcons, null, 2)};\n\nexport const JELLY_FONT_DATA_URL = ${JSON.stringify(fontDataUrl)};\n`;

  await fs.mkdir(path.dirname(outFile), { recursive: true });
  await fs.writeFile(outFile, file, "utf8");
  process.stdout.write(`Generated ${path.relative(repoRoot, outFile)}\n`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
